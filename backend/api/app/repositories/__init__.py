from typing import Protocol, List, Optional, Any, Dict
from datetime import  datetime, date

class ServeceContersRepo(Protocol):
    def list_all(self) -> List[Any]:...
    def blunk_insert(self, items: List[Dict[str, Any]]) -> None: ...

class AccessNodesRepo(Protocol):
    def list_all(self) -> List[Any]: ...
    def get_by_id(self, node_id:str)-> Optional[Any]: ...
    def bluk_insert(self, items: List[Dict[str,Any]]) -> None: ...

class WorkTypesRepo(Protocol):
    def list_all(self) -> List[Any]: ...
    def get_by_code(self, code: str) -> Optional[Any]: ...
    def bulk_insert(self, items: List[Dict[str, Any]]) -> None: ...

class StaffRepo(Protocol):
    def list_all(self) -> List[Any]: ...
    def get_by_id(self, staff_id: str) -> Optional[Any]: ...  
    def get_active(self) -> List[Any]: ...
    def bulk_insert(self, items: List[Dict[str, Any]]) -> None: ...

class OrdersRepo(Protocol):
    def list_by_date(self, plan_date: date) -> List[Any]: ...
    def get_by_id(self, order_id: str) -> Optional[Any]: ...  
    def create(self, order: Dict[str, Any]) -> Any: ...
    def update_status(self, order_id: str, status: str) -> None: ...  
    def get_risky(self, plan_date: date) -> List[Any]: ...
    def get_unassigned(self, plan_date: date) -> List[Any]: ...
    def get_pgp_candidates(self, node_id: str, window_start: datetime, window_end: datetime) -> List[Any]: ...  
    def bulk_insert(self, items: List[Dict[str, Any]]) -> None: ...

class EventsRepo(Protocol):
    def create(self, event: Dict[str, Any]) -> Any: ...
    def list_recent(self, limit: int = 50) -> List[Any]: ...

class PlansRepo(Protocol):
    def save(self, plan: Dict[str, Any]) -> Any: ...
    def get_latest(self, plan_date: date) -> Optional[Any]: ...